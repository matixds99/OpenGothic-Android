/// KeyEvent::code of events generated by touch controls starts here. Real keyboard codes are Unicode code points.
constexpr uint32_t KeyCodeBase = 0x110000u;

inline bool isKeyCode(uint32_t code) {
  return KeyCodeBase<=code && code<KeyCodeBase+uint32_t(Key::Count);
  }

inline Key keyFromCode(uint32_t code) {
  return Key(code-KeyCodeBase);
  }

inline uint64_t keyMask(Key key) {
  return uint64_t(1)<<uint32_t(key);
  }

